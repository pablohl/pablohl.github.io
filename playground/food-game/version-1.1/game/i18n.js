 // Retain the English source of static text so switching languages is reversible.
 const staticText=[];
 function captureStatic() {
  const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()) {
   const node=walker.currentNode, key=node.textContent.trim();
   if(strings[key])staticText.push({node,key});
  }
 }
 function translateStatic() {
  staticText.forEach(({node,key})=>node.textContent=t(key));
  document.getElementById('players').setAttribute('aria-label',t('Player scores'));
 }
